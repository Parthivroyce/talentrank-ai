  // Helper Methods for Service Layer
  getUserByEmail(email: string): User | undefined {
    for (const u of this.users.values()) {
      if (u.email.toLowerCase() === email.toLowerCase()) return u;
    }
    return undefined;
  }

  getUserById(id: string): User | undefined {
    return this.users.get(id);
  }

  getRequisitions(): Requisition[] {
    return Array.from(this.requisitions.values()).sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
  }

  getRequisitionById(id: string): Requisition | undefined {
    return this.requisitions.get(id);
  }

  getCandidatesByRequisition(reqId: string): Candidate[] {
    return Array.from(this.candidates.values())
      .filter((c) => c.requisitionId === reqId)
      .sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
  }

  getCandidateById(id: string): Candidate | undefined {
    return this.candidates.get(id);
  }

  getCandidateScore(candidateId: string): CandidateScore | undefined {
    for (const sc of this.candidateScores.values()) {
      if (sc.candidateId === candidateId) return sc;
    }
    return undefined;
  }

  getClientSubmissions(organizationId: string): ClientSubmission[] {
    return Array.from(this.clientSubmissions.values())
      .filter((sub) => sub.organizationId === organizationId)
      .sort((a, b) => new Date(b.submittedAt).getTime() - new Date(a.submittedAt).getTime());
  }

  addAuditLog(entry: Omit<AuditLog, 'id' | 'timestamp'>): AuditLog {
    const log: AuditLog = {
      ...entry,
      id: `aud-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
      timestamp: new Date().toISOString(),
    };
    this.auditLogs.unshift(log);
    return log;
  }
